// Offline, reproducible placement against the bundled OSM-derived geometry.
import fs from "node:fs";
import { CityPath } from "../src/city/cityPath.js";
import {
  STREET_SCENES,
  safeStreetScene,
} from "../src/city/puneStreetDetails.js";
const base = "assets/cities/pune/";
const manifest = JSON.parse(fs.readFileSync(base + "manifest.json"));
const path = new CityPath(
  JSON.parse(fs.readFileSync(base + manifest.navigation)),
  manifest,
);
const chunks = manifest.chunks.map((c) =>
  JSON.parse(fs.readFileSync(base + c.file)),
);
const original = STREET_SCENES.filter((p) => !p.id.startsWith("local-market-"));
const sites = [];
for (let anchor = 80; anchor < path.length; anchor += 180) {
  let selected;
  for (const shift of [0, -25, 25, -50, 50]) {
    const s = anchor + shift;
    const q = path.sampleAtDistance(s, {});
    if (q.elevated || path.nearJunction(s)) continue;
    for (const side of Math.floor(anchor / 180) % 2 ? [1, -1] : [-1, 1]) {
      for (const setback of [8.2, 11, 15, 19]) {
        const x = q.x + q.nx * side * (q.width / 2 + setback);
        const z = q.z + q.nz * side * (q.width / 2 + setback);
        const data = chunks.find(
          (c) => x >= c.x && x < c.x + c.size && z >= c.z && z < c.z + c.size,
        );
        if (!data) continue;
        const p = {
          id: `local-market-${anchor}`,
          s: Math.round(s),
          x: +x.toFixed(3),
          z: +z.toFixed(3),
          // The local -Z frontage faces the road on either verge.
          yaw: Math.atan2(q.nx * side, q.nz * side),
          tile: data.id,
          kind: "shops",
          district: s < 2900 || s > 9000 ? "Baner" : "Pashan approach",
          label: "Local market · स्थानिक बाजार",
        };
        if (!safeStreetScene(p, data, path)) continue;
        if (
          [...original, ...sites].some((o) => Math.hypot(o.x - x, o.z - z) < 38)
        )
          continue;
        selected = p;
        break;
      }
      if (selected) break;
    }
    if (selected) break;
  }
  if (selected) sites.push(selected);
}
fs.writeFileSync(
  "src/city/puneMarketSites.js",
  "// Generated by tools/plan-pune-markets.mjs. Fictional shops, validated offline.\nexport const MARKET_SITES = " +
    JSON.stringify(sites, null, 2) +
    ";\n",
);
console.log(
  JSON.stringify({
    markets: sites.length,
    routeMetres: path.length,
    positions: sites.map((p) => p.s),
  }),
);
